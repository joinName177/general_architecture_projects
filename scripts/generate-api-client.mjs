import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { spawn } from "node:child_process";

const specificationPath = "contracts/dify-agent-api/v1/openapi.yaml";
const digestPath = "contracts/dify-agent-api/v1/openapi.sha256";
const outputDirectory =
  process.env.DIFY_AGENT_GENERATED_OUTPUT ?? "src/generated/dify-agent-api";

const specification = await readFile(specificationPath);
const expectedDigest = (await readFile(digestPath, "utf8")).trim();
const actualDigest = createHash("sha256").update(specification).digest("hex");

if (actualDigest !== expectedDigest) {
  throw new Error("Pinned OpenAPI artifact does not match its SHA-256 digest.");
}

await new Promise((resolve, reject) => {
  const child = spawn(
    process.execPath,
    ["node_modules/@hey-api/openapi-ts/bin/run.js"],
    {
      env: { ...process.env, DIFY_AGENT_GENERATED_OUTPUT: outputDirectory },
      stdio: "inherit",
    },
  );

  child.once("error", reject);
  child.once("exit", (code) => {
    if (code === 0) {
      resolve();
      return;
    }
    reject(new Error(`OpenAPI generation exited with code ${String(code)}.`));
  });
});

const contractSource = `// Code generated by scripts/generate-api-client.mjs; DO NOT EDIT.\nexport const apiContractId = "dify-agent-api/v1";\nexport const apiContractSha256 =\n  "${actualDigest}";\n`;

await writeFile(`${outputDirectory}/contract.gen.ts`, contractSource, "utf8");
